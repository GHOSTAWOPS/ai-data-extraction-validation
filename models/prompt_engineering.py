def split_into_chunks(text):
    """
    根据“第X块：”标记将输入文本分成多个块。
    返回：一个按照块顺序排列的字符串列表，每个字符串对应一个块的内容。
    """
    # 使用正则表达式匹配分块起始，如：第0块：、第1块：
    pattern = r"(第\d+块：)"

    # 在每个匹配点插入分隔符（保留标记作为内容的一部分）
    parts = re.split(pattern, text)

    # re.split 会保留括号里的内容作为单独项，所以组合块名和块内容
    chunks = []
    for i in range(1, len(parts), 2):
        chunk_title = parts[i]  # 第X块：
        chunk_content = parts[i + 1].strip()  # 内容部分
        chunks.append(f"{chunk_title}{chunk_content}")

    return chunks